import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
const {validPoint, distanceKm, nearby, nearestCity, routeUrl, createOriginState} = require('./norway-catalog.js');
const gran = {latitude: 60.3592, longitude: 10.5728};
const oslo = {latitude: 59.9139, longitude: 10.7522};
assert.equal(distanceKm(gran, gran), 0);
assert.ok(distanceKm(gran, oslo) > 49 && distanceKm(gran, oslo) < 51, 'Gran–Oslo should be approximately 50 km in a straight line');
assert.ok(Math.abs(distanceKm(gran, oslo) - distanceKm(oslo, gran)) < 0.00001);
assert.equal(distanceKm(gran, {latitude: null, longitude: 0}), null);
assert.equal(validPoint({latitude: 91, longitude: 0}), false);
assert.equal(validPoint({latitude: 0, longitude: 181}), false);
assert.equal(validPoint({latitude: '60', longitude: 10}), false);
const rows = [{id:'unknown', name:'No coordinates'}, {id:'oslo', ...oslo}, {id:'gran', ...gran}];
assert.deepEqual(nearby(rows, gran, '20').map(r => r.id), ['gran']);
assert.deepEqual(nearby(rows, gran, '100').map(r => r.id), ['gran', 'oslo']);
assert.deepEqual(nearby(rows, gran, 'all').map(r => r.id), ['gran', 'oslo', 'unknown']);
assert.deepEqual(nearby(rows, null, '20'), [], 'No invented origin for a radius search');
assert.deepEqual(nearby(rows, null, 'all').map(r => r.id), ['unknown', 'oslo', 'gran']);
assert.equal(nearby(rows, null, 'all')[0].catalogueDistance, null);
assert.equal(nearestCity(gran, [{name:'Oslo', ...oslo}, {name:'Gran', ...gran}]).name, 'Gran');
assert.equal(nearestCity({latitude:60.36, longitude:10.58}, [{name:'Oslo', ...oslo}, {name:'Gran', ...gran}]).name, 'Gran');
assert.equal(nearestCity(gran, [{name:'No coordinates'}]), null);
assert.equal(nearestCity(gran, [{name:'Oslo', ...oslo}], 20), null, 'Do not name a settlement outside the maximum distance');
assert.equal(nearestCity({latitude:48.8566, longitude:2.3522}, [{name:'Oslo', ...oslo}], 50), null, 'GPS outside Norway must not be presented as a Norwegian town');
assert.equal(nearestCity(gran, [], 50), null, 'Missing local gazetteer means GPS without a fabricated town');
const route = new URL(routeUrl({name:'A café', ...oslo}, gran));
assert.equal(route.origin, 'https://www.google.com');
assert.equal(route.searchParams.get('destination'), '59.9139,10.7522');
assert.equal(route.searchParams.get('origin'), '60.3592,10.5728');
assert.equal(new URL(routeUrl({name:'Unknown coordinates', address:'Alta, Norway'}, null)).searchParams.has('origin'), false);
assert.ok(new URL(routeUrl({name:'Unknown coordinates', address:'Alta, Norway'}, null)).searchParams.get('destination').includes('Alta'));
const approximate = new URL(routeUrl({name:'Flyt Jevnaker', ...gran, coordinatePrecision:'area'}, oslo));
assert.equal(approximate.searchParams.get('destination'), 'Flyt Jevnaker, Norway', 'Approximate area coordinates must not become the navigation destination');
const suppliedAreaRoute = new URL(routeUrl({name:'Flyt Jevnaker', ...gran, coordinatePrecision:'area', directionsUrl:'https://www.google.com/maps/dir/?api=1&destination=Flyt+Jevnaker'}, oslo));
assert.equal(suppliedAreaRoute.searchParams.get('destination'), 'Flyt Jevnaker');
assert.equal(suppliedAreaRoute.searchParams.get('origin'), '59.9139,10.7522');
const parkingRoute = new URL(routeUrl({name:'Steinsdalsfossen', latitude:60.3706, longitude:6.1033, directionsUrl:'https://www.google.com/maps/dir/?api=1&destination=Steinsdalsfossen+parking&origin=old-session'}, gran));
assert.equal(parkingRoute.searchParams.get('destination'), 'Steinsdalsfossen parking', 'Explicit safe parking destination must survive instead of waterfall coordinates');
assert.equal(parkingRoute.searchParams.get('origin'), '60.3592,10.5728');
assert.equal(new URL(routeUrl({name:'Steinsdalsfossen', directionsUrl:parkingRoute.href}, null)).searchParams.has('origin'), false, 'Previous-session origin must not leak into a new session');
const numericArea = new URL(routeUrl({name:'Flyt Jevnaker', ...gran, coordinatePrecision:'area', directionsUrl:'https://www.google.com/maps/dir/?api=1&destination=60.3592,10.5728'}, null));
assert.equal(numericArea.searchParams.get('destination'), 'Flyt Jevnaker, Norway', 'Area coordinates in an explicit URL must also fall back to venue name');
const state = createOriginState(), token = state.beginGPS();
state.set({...gran, name:'Gran'});
assert.equal(state.acceptGPS(token, oslo), false, 'Late GPS callback must not override manual town');
assert.equal(state.current.name, 'Gran');
const oldGPS = state.beginGPS(), newGPS = state.beginGPS();
assert.equal(state.acceptGPS(oldGPS, oslo), false, 'Late older GPS request is ignored');
assert.equal(state.acceptGPS(newGPS, oslo), true);
assert.equal(state.current.latitude, oslo.latitude);
state.set(null); assert.equal(state.current, null);
assert.equal(state.isCurrent(newGPS), false);
console.log('Catalogue geography: distance, radius, unknown coordinates, directions and GPS races passed.');
